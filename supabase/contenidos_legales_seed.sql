7. FUNCIONES SEGÚN PLAN
Los límites de cada plan (Me Gustas diarios, Superlikes, Deshacer, perfiles en Cerca de ti, etc.) se describen en la app y pueden ajustarse para mejorar el servicio. El uso abusivo o automatizado puede limitarse temporalmente.

