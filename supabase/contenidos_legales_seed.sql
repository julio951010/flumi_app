Te comprometes a no: acosar, amenazar, insultar o discriminar a otros usuarios; publicar contenido sexual explícito, violento, ilegal o que explote a menores; usar Flumi con fines comerciales, spam, estafas o para solicitar dinero; suplantar a otra persona; intentar acceder a cuentas ajenas o vulnerar la seguridad de la app; usar bots, scrapers o medios automatizados.

