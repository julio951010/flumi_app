Flumi es exclusivamente para personas mayores de 18 años. Al registrarte declaras tener al menos 18 años. Nos reservamos el derecho de solicitar verificación de edad y de suspender o eliminar cualquier cuenta de la que sospechemos que pertenece a un menor, sin previo aviso ni reembolso.

3. TU CUENTA
Eres responsable de mantener la confidencialidad de tus credenciales y de toda actividad realizada con tu cuenta. Debes proveer información veraz en tu perfil. Solo puedes tener una cuenta personal; las cuentas falsas, duplicadas o de terceros están prohibidas.

