Conservas los derechos sobre tus fotos y textos, pero nos otorgas una licencia para mostrarlos dentro de Flumi a otros usuarios según tus ajustes de visibilidad. Garantizas que tu contenido es tuyo y no infringe derechos de terceros. Podemos retirar cualquier contenido que viole estos términos.

